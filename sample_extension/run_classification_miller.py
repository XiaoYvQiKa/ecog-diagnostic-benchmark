# -*- coding: utf-8 -*-
"""Classification methods on the added Miller subjects (jc, wc).

Runs the four classification methods (CSP+LDA, Spectral+LGB, EEGNet,
EEG-Conformer) on the prep outputs, reusing the classification/ feature,
model, and evaluation pipeline and replacing only the data source.

The prep outputs provide ecog (raw amplifier units, 1000 Hz), flex (de-based
relative flexion, 25 Hz, equivalent to the BCI train_dg), and glove-threshold
labels (25 Hz). load_miller reproduces the BCI load_subject interface:
per-channel z-score on train statistics, flex as the data-glove trace, and
labels regenerated by generate_labels (deterministic, identical to the prep
labels).

Seed protocol matches the original published benchmark: all four methods use
5 seeds [42, 142, 242, 342, 442]. CSP+LDA and Spectral+LGB are deterministic in
this configuration, whereas EEGNet and EEG-Conformer vary across seeds.

Usage:
    python run_classification_miller.py jc wc
"""
import json
import sys
import time

import numpy as np

import paths as P

CLS_DIR = P.PROJECT_ROOT / "Classification"
sys.path.insert(0, str(CLS_DIR))

from common.config import BenchmarkConfig, FINGER_NAMES  # noqa: E402
from common.data_loader import generate_labels, window_majority_labels  # noqa: E402
from common.features import extract_spectral_features, extract_csp_features  # noqa: E402
from common.models import CSPLDA, LightGBMClassifier  # noqa: E402
from common.evaluation import evaluate_classification  # noqa: E402
from common.dl_utils import (downsample_ecog, extract_trials,  # noqa: E402
                                  extract_test_trials, TRIAL_SAMPLES)

SEEDS_TRAD = [42, 142, 242, 342, 442]
SEEDS_DL = [42, 142, 242, 342, 442]  # 5 seeds, aligned with the published benchmark


def load_miller(subject: str):
    """Load prep outputs and reproduce the BCI load_subject interface."""
    ecog_train = np.load(P.PREP_DIR / subject / "ecog_train.npy").astype(np.float64)  # (T, ch)
    ecog_test = np.load(P.PREP_DIR / subject / "ecog_test.npy").astype(np.float64)
    flex_train = np.load(P.PREP_DIR / subject / "flex_train.npy").astype(np.float64)  # (T25, 5)
    flex_test = np.load(P.PREP_DIR / subject / "flex_test.npy").astype(np.float64)

    train_ecog = ecog_train.T   # (ch, T)
    test_ecog = ecog_test.T
    train_mean = train_ecog.mean(axis=1, keepdims=True)
    train_std = train_ecog.std(axis=1, keepdims=True)
    train_ecog = (train_ecog - train_mean) / (train_std + 1e-8)
    test_ecog = (test_ecog - train_mean) / (train_std + 1e-8)

    return {
        "train_ecog": train_ecog,
        "test_ecog": test_ecog,
        "train_dg": flex_train,
        "test_dg": flex_test,
        "n_channels": train_ecog.shape[0],
    }


def run_traditional_miller(subject, seed, methods, cfg, verbose=False):
    """Traditional methods (CSP+LDA, Spectral+LGB) for one subject and seed."""
    d = load_miller(subject)
    train_ecog, test_ecog = d["train_ecog"], d["test_ecog"]
    train_dg, test_dg = d["train_dg"], d["test_dg"]

    train_labels = generate_labels(train_dg)
    train_max = train_dg.max(axis=0)
    test_labels = generate_labels(test_dg, max_angles=train_max)

    feat_cfg = cfg.features
    result = {"subject": subject, "seed": seed, "results": {}}

    need_spectral = "lgb" in methods
    if need_spectral:
        X_spec_train, _ = extract_spectral_features(train_ecog, feat_cfg)
        X_spec_test, _ = extract_spectral_features(test_ecog, feat_cfg)
        maj_tr = window_majority_labels(train_labels, feat_cfg.window_samples, feat_cfg.step_samples)
        maj_te = window_majority_labels(test_labels, feat_cfg.window_samples, feat_cfg.step_samples)
        y_cls_tr = maj_tr[:len(X_spec_train)]
        y_cls_te = maj_te[:len(X_spec_test)]

    if "csp" in methods:
        csp_win = int(cfg.csp.window_ms * feat_cfg.fs / 1000)
        csp_step = int(cfg.csp.step_ms * feat_cfg.fs / 1000)
        maj_csp_tr = window_majority_labels(train_labels, csp_win, csp_step)
        maj_csp_te = window_majority_labels(test_labels, csp_win, csp_step)
        X_csp_train, _, csp_filt = extract_csp_features(
            train_ecog, maj_csp_tr, cfg.csp, feat_cfg, csp_filters=None)
        y_csp_tr = maj_csp_tr[:len(X_csp_train)]
        X_csp_test, _, _ = extract_csp_features(
            test_ecog, maj_csp_te, cfg.csp, feat_cfg, csp_filters=csp_filt)
        y_csp_te = maj_csp_te[:len(X_csp_test)]

    if "lgb" in methods:
        import dataclasses
        lgb_cfg = dataclasses.replace(cfg.lgb, random_state=seed)
        model = LightGBMClassifier(lgb_cfg)
        model.fit(X_spec_train, y_cls_tr)
        yp = model.predict(X_spec_test)
        ypb = model.predict_proba(X_spec_test)
        m = evaluate_classification(y_cls_te, yp, y_proba=ypb)
        m["train_time"] = model.train_time
        m["infer_time"] = model.infer_time
        m["n_params"] = None
        result["results"]["lgb"] = m

    if "csp" in methods:
        model = CSPLDA(cfg.csp)
        model.fit(X_csp_train, y_csp_tr)
        yp = model.predict(X_csp_test)
        ypb = model.predict_proba(X_csp_test)
        m = evaluate_classification(y_csp_te, yp, y_proba=ypb)
        m["train_time"] = model.train_time
        m["infer_time"] = model.infer_time
        m["n_params"] = X_csp_train.shape[1]
        result["results"]["csp"] = m

    return result


def train_dl(model, Xtr_t, ytr_t, Xte_t, yte_t, lr, betas, batch_size, n_epochs, patience, mixup_alpha=0.0):
    """Train one DL model on trial data (identical to common.run_dl.train_dl)."""
    import torch
    import torch.nn as nn

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = model.to(device)
    n_params = sum(p.numel() for p in model.parameters())
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr, betas=betas)

    n_train = len(Xtr_t)
    indices = np.arange(n_train)
    best_loss = float("inf")
    best_state = None
    patience_counter = 0
    t0 = time.time()

    for epoch in range(n_epochs):
        np.random.shuffle(indices)
        model.train()
        train_loss = 0.0
        for start in range(0, n_train, batch_size):
            batch_idx = indices[start:start + batch_size]
            Xb = Xtr_t[batch_idx].to(device)
            yb = ytr_t[batch_idx].to(device)
            if mixup_alpha > 0:
                lam = np.random.beta(mixup_alpha, mixup_alpha)
                perm = torch.randperm(len(Xb))
                X_mix = lam * Xb + (1 - lam) * Xb[perm]
                optimizer.zero_grad()
                logits = model(X_mix)
                loss = lam * criterion(logits, yb) + (1 - lam) * criterion(logits, yb[perm])
            else:
                optimizer.zero_grad()
                logits = model(Xb)
                loss = criterion(logits, yb)
            loss.backward()
            optimizer.step()
            train_loss += loss.item()

        n_batches = max(1, (n_train + batch_size - 1) // batch_size)
        avg_loss = train_loss / n_batches
        if avg_loss < best_loss - 1e-4:
            best_loss = avg_loss
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= patience:
                break

    train_time = time.time() - t0
    if best_state is not None:
        model.load_state_dict(best_state)
    model.eval()
    with torch.no_grad():
        logits = model(Xte_t.to(device))
        proba = torch.softmax(logits, dim=1).cpu().numpy()
        pred = torch.argmax(logits, dim=1).cpu().numpy()
    return pred, proba, train_time, 0.0, n_params


def run_dl_miller(subject, seed, n_epochs=100, patience=15, mixup_alpha=0.0, verbose=False):
    """Trial-based DL (EEGNet, EEG-Conformer) for one subject and seed."""
    import random
    import torch
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    np.random.seed(seed)
    random.seed(seed)

    d = load_miller(subject)
    ecog_train_500 = downsample_ecog(d["train_ecog"])
    ecog_test_500 = downsample_ecog(d["test_ecog"])
    train_max = d["train_dg"].max(axis=0)
    Xtr, ytr = extract_trials(ecog_train_500, d["train_dg"], seed=seed)
    Xte, yte = extract_test_trials(ecog_test_500, d["test_dg"], train_max=train_max)

    if verbose:
        unique_tr, cnt_tr = np.unique(ytr, return_counts=True)
        unique_te, cnt_te = np.unique(yte, return_counts=True)
        print(f"  {subject} trials: train={len(ytr)}, test={len(yte)}")
        print(f"    Train dist: {dict(zip(unique_tr, cnt_tr))}")
        print(f"    Test dist:  {dict(zip(unique_te, cnt_te))}")

    Xtr_t = torch.FloatTensor(Xtr)
    ytr_t = torch.LongTensor(ytr)
    Xte_t = torch.FloatTensor(Xte)
    yte_t = torch.LongTensor(yte)
    n_ch = Xtr.shape[1]
    results = {}

    from braindecode.models import EEGNet
    model = EEGNet(n_outputs=6, n_chans=n_ch, n_times=TRIAL_SAMPLES,
                   F1=8, D=2, F2=16, kernel_length=250,
                   pool_mode="mean", drop_prob=0.5, final_conv_length="auto")
    yp, ypb, ttrain, tinfer, npar = train_dl(
        model, Xtr_t, ytr_t, Xte_t, yte_t,
        lr=1e-3, betas=(0.9, 0.999), batch_size=64,
        n_epochs=n_epochs, patience=patience, mixup_alpha=mixup_alpha)
    ev = evaluate_classification(yte, yp)
    ev["train_time"] = ttrain
    ev["infer_time"] = tinfer
    ev["n_params"] = npar
    results["eegnet"] = ev

    from braindecode.models import EEGConformer
    model = EEGConformer(n_outputs=6, n_chans=n_ch,
                         n_filters_time=40, filter_time_length=50,
                         pool_time_length=150, pool_time_stride=30,
                         drop_prob=0.5, num_layers=6, num_heads=10,
                         att_drop_prob=0.5, n_times=TRIAL_SAMPLES,
                         final_fc_length="auto")
    yp, ypb, ttrain, tinfer, npar = train_dl(
        model, Xtr_t, ytr_t, Xte_t, yte_t,
        lr=2e-4, betas=(0.5, 0.999), batch_size=72,
        n_epochs=n_epochs, patience=patience, mixup_alpha=mixup_alpha)
    ev2 = evaluate_classification(yte, yp)
    ev2["train_time"] = ttrain
    ev2["infer_time"] = tinfer
    ev2["n_params"] = npar
    results["eegconformer"] = ev2

    return {
        "subject": subject,
        "seed": seed,
        "results": results,
        "n_trials": {"train": len(ytr), "test": len(yte)},
    }


def main():
    subs = sys.argv[1:] if len(sys.argv) > 1 else ["jc", "wc"]
    cfg = BenchmarkConfig()

    trad_results = []
    dl_results = []
    t0 = time.time()

    for subj in subs:
        for seed in SEEDS_TRAD:
            print(f"[trad] {subj} seed={seed}")
            r = run_traditional_miller(subj, seed, ["lgb", "csp"], cfg)
            trad_results.append(r)

    for subj in subs:
        for seed in SEEDS_DL:
            print(f"[dl] {subj} seed={seed}")
            r = run_dl_miller(subj, seed, verbose=True)
            dl_results.append(r)

    runtime_s = time.time() - t0
    out = {
        "experiment": "classification_miller",
        "subjects": subs,
        "seeds_trad": SEEDS_TRAD,
        "seeds_dl": SEEDS_DL,
        "traditional": trad_results,
        "dl": dl_results,
        "runtime_s": runtime_s,
    }
    out_path = P.OUT_DIR / "classification_miller_results.json"
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False))
    print(f"\nsaved -> {out_path}  (runtime {runtime_s/60:.1f} min)")


if __name__ == "__main__":
    main()
